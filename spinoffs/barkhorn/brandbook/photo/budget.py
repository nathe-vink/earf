def table(rows, title):
    print(f"## {title}\n\n| Item | Lean | Planned | Basis |\n|---|---|---|---|")
    lo = sum(r[1] for r in rows); hi = sum(r[2] for r in rows)
    for r in rows: print(f"| {r[0]} | ${r[1]:,} | ${r[2]:,} | {r[3]} |")
    print(f"| Contingency, 10% | ${lo*0.1:,.0f} | ${hi*0.1:,.0f} | |")
    print(f"| **Total** | **${lo*1.1:,.0f}** | **${hi*1.1:,.0f}** | |\n")
    return lo*1.1, hi*1.1

