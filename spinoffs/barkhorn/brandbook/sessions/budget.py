"""Session 00: the record's budget at 300 and 500, the price, and break-even.

Run: python3 budget.py > BUDGET.md. Every figure is est. unless a source is named; sources were read 2026-10-31.
  Precision Record Pressing, precisionpressing.com/pricing: translucent colour, standard weight, all in (DMM cutting,
    plating, 5 test pressings, full-colour jacket and labels, poly sleeves, assembly, shrink): 300 $2,396, 500 $3,067.
    180 g extra not published.
  United Record Pressing, customers.urpressing.com/180g.php: item prices (180 g $1.96, colour +$0.69, setup $95,
    lacquer mastering $330, plating $290, tests $100, labels $160, shrink $0.15, 500 jackets from $695).
  Different Fur Studios (mobile: engineer $60/hr, 4 h minimum; gear $100/day; travel $25 in SF);
  Wildplum Recordings (remote: 16 tracks $800-1,200, 24 tracks $1,400-2,500); House Call ($300 a song mixing, SoundBetter).
  Mastering for vinyl $150-400 (Chartlex 2026, secondary). HFA Songfile $16/$14 a song; statutory 13.1 c (2026).
"""

N = (300, 500)

def costs(n, cover_songs=0, songs=8):
    c = {}
    c["Recording: engineer and mobile multitrack rig, with a backup recorder (Wildplum's 24-track range, midpoint)"] = 1950
    c["Mixing (about $300 a song for 8 songs, House Call's average)"] = 300 * songs
    c["Mastering for vinyl"] = 300
    c["Pressing, all in: DMM cut, plating, 5 tests, printed jacket and labels, sleeves, shrink (Precision, translucent)"] = {300: 2396, 500: 3067}[n]
    c["180 g over standard weight (not published; about $0.50 a record)"] = 0.50 * n
    c["Freight from the plant to San Francisco"] = {300: 250, 500: 350}[n]
    c["Numbering by hand: a stamp, ink, an afternoon"] = 100
    c["Jacket: cover photograph licence and print-ready artwork"] = 500
    c["Mechanical licences (8 songs, own or covers, 13.1 c each a copy; Songfile fees on covers)"] = songs * 0.131 * n + sum(16 if i < 5 else 14 for i in range(cover_songs))
    c["The artist's fee for the night (a trio; not recouped)"] = 1500
    sub = sum(c.values())
    c["Contingency, 10%"] = 0.10 * sub
    return c

PRICE = 40           # IDEAS.md (a): about $40 is typical for a numbered coloured pressing (est.)
FEES = 0.03          # card processing on direct sales (est.)
ROYALTY_B = 6        # option B in RIGHTS.md: $6 an LP sold
ARTIST_COPIES = 25

def main():
    p = print
    p("# Session 00: the record's budget (est.)\n")
    p("Generated by `budget.py`; sources in its header. **Every figure is est. unless a source is named.** Shipping to")
    p("buyers is charged at cost. The plant in this budget is Precision because it is the only one that publishes an all-in")
    p("price; United Record Pressing's item prices sum to about $1,950 for 300 and $2,750 for 500 (with its $330 lacquer")
    p("mastering, before 300 jackets and freight); Pirates Press and Hand Drawn publish none. The quotes (`QUOTES.md`)")
    p("replace these figures.\n")
    cs = {n: costs(n, cover_songs=4) for n in N}
    p("| Item | 300 | 500 |\n|---|---|---|")
    for k in cs[300]:
        p(f"| {k} | ${cs[300][k]:,.0f} | ${cs[500][k]:,.0f} |")
    tot = {n: sum(cs[n].values()) for n in N}
    p(f"| **Total** | **${tot[300]:,.0f}** | **${tot[500]:,.0f}** |")
    p(f"| A record | ${tot[300] / 300:,.2f} | ${tot[500] / 500:,.2f} |\n")
    p("(Assumes eight songs, four of them covers licensed through Songfile; the artist's own songs at the statutory rate.)\n")
    p(f"## The price, and break-even\n")
    p(f"**Price: ${PRICE}** a numbered LP (IDEAS.md (a), est.), sold at the debut, on earf.world, through the artist, and")
    p(f"with the Kickstarter as an add-on. {ARTIST_COPIES} copies go to the artist free.\n")
    for opt, roy in (("Option B: $6 a record to the artist, from the first copy", ROYALTY_B),):
        p(f"**{opt}.** Each sale nets ${PRICE * (1 - FEES) - roy:,.2f} after card fees and the royalty.\n")
        p("| | 300 | 500 |\n|---|---|---|")
        net = PRICE * (1 - FEES) - roy
        for n in N:
            pass
        sale = {n: n - ARTIST_COPIES for n in N}
        p(f"| Records to sell | {sale[300]} | {sale[500]} |")
        p(f"| Break-even, records sold | **{tot[300] / net:,.0f}** | **{tot[500] / net:,.0f}** |")
        p(f"| Receipts if all sell | ${sale[300] * PRICE:,.0f} | ${sale[500] * PRICE:,.0f} |")
        m = lambda v: f"${v:,.0f}" if v >= 0 else f"−${-v:,.0f}"
        p(f"| Left to EARF if all sell | {m(sale[300] * net - tot[300])} | {m(sale[500] * net - tot[500])} |\n")
    # option A: 50/50 of net after recoupment
    p("**Option A: 50% of net receipts to the artist after costs are recouped.** Break-even comes sooner, since nothing is paid out")
    p("until costs are recouped; past it, the artist and EARF split the rest.\n")
    p("| | 300 | 500 |\n|---|---|---|")
    netA = PRICE * (1 - FEES)
    for n in N:
        pass
    p(f"| Break-even, records sold | **{tot[300] / netA:,.0f}** | **{tot[500] / netA:,.0f}** |")
    m = lambda v: f"${v:,.0f}" if v >= 0 else f"−${-v:,.0f}"
    p(f"| Each side's half if all sell | {m(((300 - ARTIST_COPIES) * netA - tot[300]) / 2)} | {m(((500 - ARTIST_COPIES) * netA - tot[500]) / 2)} |\n")
    # what a $45 price does
    for pr in (45, 50):
        net = pr * (1 - FEES) - ROYALTY_B
        p(f"- At **${pr}**, option B breaks even at {tot[300] / net:,.0f} (300) or {tot[500] / net:,.0f} (500).")
    p("")
    p("**At $40, 300 copies don't pay for themselves**: break-even is more records than there are to sell. Three levers,")
    p("in order of preference:\n")
    net50 = 50 * (1 - FEES) - ROYALTY_B
    p(f"1. **Price the numbered LP at $50** (est.; it's an edition of 300 from one night, numbered): break-even {tot[300] / net50:,.0f} of 275.")
    p(f"2. **A partner pays for the pressing** (about $3,000): at $50, break-even falls to {(tot[300] - 3000) / net50:,.0f}, and"
      f" selling out leaves about ${275 * net50 - tot[300] + 3000:,.0f}.")
    p(f"3. **Press 500**: a record costs ${tot[500] / 500:,.2f} instead of ${tot[300] / 300:,.2f}, but 500 is a lot of one live set to sell.\n")
    p("**Recommended: 300 at $50, with the record partner paying the pressing.** The cheapest single saving after that is")
    p("the mix: a live set mixed as one performance, not song by song, could cost half (ask the engineer).\n")
    p("## How it ties to the record-label partner\n")
    p("PARTNERS.md's third email asks a label or shop for \"the records, the set and the Session in kind, or a contribution")
    p("toward the pressing\". The pressing, freight and numbering come to about "
      f"${cs[300][list(cs[300])[3]] + cs[300][list(cs[300])[4]] + cs[300][list(cs[300])[5]] + 100:,.0f} at 300 (est.).")
    p("So:")
    p("- **A partner who pays for the pressing** (about $3,000) takes break-even at 300 from about "
      f"{tot[300] / (PRICE * (1 - FEES) - ROYALTY_B):,.0f} to about {(tot[300] - 3000) / (PRICE * (1 - FEES) - ROYALTY_B):,.0f} records,")
    p("  and is named on the jacket (\"pressed with [partner]\").")
    p("- **A label co-release** (for example a reissue label that already distributes to shops) could take 100 copies at")
    p("  wholesale, about half of retail (est.), into record shops: less margin, far more reach, and the partner's name on the spine.")
    p("- **A shop partner** sells it over its counter and hosts a listening; it's paid as any stockist is.\n")

if __name__ == "__main__":
    main()
