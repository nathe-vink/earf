"""Kickstarter kit: reward tiers, unit economics at 50 and 100 units, and the goal.

Every number is an estimate (est.) unless its source is named. Run: python3 economics.py > ECONOMICS.md
Sources:
  lamps lane, r32-lamps-final, spinoffs/barkhorn/companions/README.md (a run of 200: parts and tooling, landed),
    out-dome-pendant/bom.md (Hemisphere, one off, $4,572), out-orb-table/bom.md (Core, one off, $2,027),
    launch/lab-rfq/README.md (R3's certification estimates)
  R4-market-pricing.md (r46-owner-notes): list $1,200 / $750; Founders' $1,700 / $1,100
  Kickstarter help, checked 2026-10-31: 5% platform fee; Stripe processing "roughly 3-5%"
"""

# --- the lamps lane's run-of-200 figures (est., theirs) ----------------------------------------
RUN200 = {  # parts per unit, moulds (a one-off set), landed per unit at 200
    "Hemisphere": dict(parts=200, moulds=3900, landed=250),
    "Core": dict(parts=195, moulds=1500, landed=235),
}
SCALE = {200: 1.00, 100: 1.11, 50: 1.23}   # small-batch premium on parts: setups spread over fewer pieces (est.)
ASSEMBLY = {100: 40, 50: 50}               # assembly, finishing, QC and freight in, a unit (est.; the lane's landed figure carries about $30 at 200)
PACK = {"Hemisphere": {100: 18, 50: 24},   # the drum: through-dyed board, pulp insert, print (est.)
        "Core": {100: 16, 50: 22}}         # the cube: board, moulded pulp (est.)
FULFIL = 10                                # pick, pack, label, from the studio or a small 3PL, an order (est.)
FEES = 0.085                               # 5% Kickstarter + about 3.5% Stripe (Kickstarter help: 3-5%)
RESERVE = 0.03                             # breakage, returns and replacement shades, of the pledge (est.)

# --- certification, R3's ranges via the lab RFQ (est.) -----------------------------------------
CERT = {
    "Core": [("FCC Part 15B", 1500, 3500), ("DOE Appendix Y on the system", 1500, 4000),
             ("CEC MAEDbS listing (before any California sale)", 0, 1000), ("UL 153 + Supplement SA listing", 8000, 20000)],
    "Hemisphere": [("FCC Part 15B (the LED driver)", 1500, 3500), ("UL 153 listing, plug-in swag version", 6000, 15000)],
}

# --- tiers (prices proposed here; list and Founders' from R4) ----------------------------------
TIERS = [
    # name, product, units in the reward, pledge, limit, note
    ("Core, Early Bird", "Core", 1, 650, "first 40", "13% under list"),
    ("Core", "Core", 1, 695, "", "7% under list"),
    ("Core, a pair", "Core", 2, 1290, "", "two balls, any two tints"),
    ("Core, Numbered Edition", "Core", 1, 1100, "8 a tint, 64", "numbered, signed; R4's Founders' price"),
    ("Hemisphere, Early Bird", "Hemisphere", 1, 1050, "first 30", "12.5% under list"),
    ("Hemisphere", "Hemisphere", 1, 1120, "", "7% under list"),
    ("Hemisphere, a set of two", "Hemisphere", 2, 2090, "", "two pendants, over a table"),
    ("Hemisphere, Numbered Edition", "Hemisphere", 1, 1700, "8 a tint, 64", "numbered, signed; R4's Founders' price"),
    ("The pair of lamps", "Both", 1, 1690, "", "one Core and one Hemisphere"),
]
LIST = {"Core": 750, "Hemisphere": 1200}


def unit_cost(product, n, tooling=True):
    r = RUN200[product]
    c = r["parts"] * SCALE[n] + ASSEMBLY[n] + PACK[product][n]
    if tooling:
        c += r["moulds"] / n
    return c


def row(name, product, units, pledge, n):
    prods = ["Core", "Hemisphere"] if product == "Both" else [product] * units
    goods = sum(unit_cost(p, n) for p in prods)
    fees = pledge * FEES
    reserve = pledge * RESERVE
    margin = pledge - goods - fees - reserve - FULFIL
    return goods, fees, reserve, margin


def cert_total(product, which):
    i = 1 if which == "low" else 2
    return sum(x[i] for x in CERT[product])


def main():
    p = print
    p("# Kickstarter kit: unit economics and the goal\n")
    p("Generated by `economics.py`. **Every figure is an estimate (est.)** unless a source is named in the script's header.")
    p("Shipping is charged to backers at cost and is not in these sums. Sales tax is collected on top where Kickstarter")
    p("collects it, and is not revenue.\n")
    p("## Cost of one unit, before fees (est.)\n")
    p("| | Core at 50 | Core at 100 | Hemisphere at 50 | Hemisphere at 100 |\n|---|---|---|---|---|")
    lines = [
        ("Parts (the lane's run-of-200 parts × a small-batch premium)", lambda pr, n: RUN200[pr]["parts"] * SCALE[n]),
        ("Assembly, finishing, QC, freight in", lambda pr, n: ASSEMBLY[n]),
        ("Packaging (the drum or the cube)", lambda pr, n: PACK[pr][n]),
        ("Moulds spread over the run", lambda pr, n: RUN200[pr]["moulds"] / n),
        ("**Cost of goods**", lambda pr, n: unit_cost(pr, n)),
    ]
    for label, f in lines:
        p(f"| {label} | " + " | ".join(f"${f(pr, n):,.0f}" for pr in ("Core", "Hemisphere") for n in (50, 100)) + " |")
    p(f"\nFor scale, the lane's own figure at a run of 200 is about ${RUN200['Core']['landed']} (Core) and"
      f" ${RUN200['Hemisphere']['landed']} (Hemisphere) landed; the one-off prototypes are $2,027 and $4,572.")
    p("Certification is a fixed cost, in the goal below, not in these sums.\n")

    for n in (50, 100):
        p(f"## Margin per reward, at a run of {n} of each lamp (est.)\n")
        p("| Reward | Pledge | Limit | Goods | Fees 8.5% | Reserve 3% | Fulfilment | **Margin** | Margin % |")
        p("|---|---|---|---|---|---|---|---|---|")
        for name, product, units, pledge, limit, note in TIERS:
            g, fe, rs, m = row(name, product, units, pledge, n)
            p(f"| {name} | ${pledge:,} | {limit or 'none'} | ${g:,.0f} | ${fe:,.0f} | ${rs:,.0f} | ${FULFIL} | **${m:,.0f}** | {m / pledge:.0%} |")
        p("")

    p("## Certification before the first lamp ships (R3's ranges, est.)\n")
    p("| Product | Test or listing | Low | High |\n|---|---|---|---|")
    for pr in ("Core", "Hemisphere"):
        for name, lo, hi in CERT[pr]:
            p(f"| {pr} | {name} | ${lo:,} | ${hi:,} |")
    lo = cert_total("Core", "low") + cert_total("Hemisphere", "low")
    hi = cert_total("Core", "high") + cert_total("Hemisphere", "high")
    p(f"| **Both** | | **${lo:,}** | **${hi:,}** |\n")

    # the goal: fixed costs the campaign must carry, met by the margin on a minimum run
    fixed = [
        ("Certification, both lamps (midpoint of R3's range)", (lo + hi) / 2),
        ("A second Hemisphere shell mould, for a run's wear (est.)", 1500),
        ("Test units destroyed in certification: two of each (est.)", 2 * unit_cost("Core", 50) + 2 * unit_cost("Hemisphere", 50)),
        ("Photography and the film, of real prototypes (est.)", 3000),
        ("Pledge manager and survey (est.)", 1000),
        ("Advertising in launch week, to the waitlist's lookalikes (est.)", 4000),
    ]
    fixed_total = sum(v for _, v in fixed)
    contingency = 0.15 * fixed_total
    p("## The goal (est.)\n")
    p("What the campaign must carry beyond the cost of the lamps it sells. The moulds for the prototypes are paid before")
    p("it, from the pre-seed; the run's share of them is in each unit above, so it returns to the business.\n")
    p("| Fixed cost | Amount |\n|---|---|")
    for k, v in fixed:
        p(f"| {k} | ${v:,.0f} |")
    p(f"| Contingency, 15% | ${contingency:,.0f} |")
    p(f"| **Fixed, in all** | **${fixed_total + contingency:,.0f}** |\n")

    # a minimum run: 50 Core and 50 Hemisphere, a typical mix of rewards (est.)
    mix = {"Core, Early Bird": 25, "Core": 15, "Core, a pair": 2, "Core, Numbered Edition": 6,
           "Hemisphere, Early Bird": 20, "Hemisphere": 14, "Hemisphere, a set of two": 2, "Hemisphere, Numbered Edition": 6,
           "The pair of lamps": 4}
    t = {x[0]: x for x in TIERS}
    pledged = sum(t[k][3] * q for k, q in mix.items())
    margin = sum(row(*t[k][:4], 50)[3] * q for k, q in mix.items())
    units_core = sum(q * (t[k][2] if t[k][1] == "Core" else (1 if t[k][1] == "Both" else 0)) for k, q in mix.items())
    units_hemi = sum(q * (t[k][2] if t[k][1] == "Hemisphere" else (1 if t[k][1] == "Both" else 0)) for k, q in mix.items())
    p(f"**A minimum run** ({units_core} Core, {units_hemi} Hemisphere, an assumed mix: {sum(mix.values())} backers):")
    p(f"pledges ${pledged:,.0f}; margin after goods, fees, reserve and fulfilment ${margin:,.0f};"
      f" fixed costs ${fixed_total + contingency:,.0f}; **{'left' if margin >= fixed_total + contingency else 'short by'} ${abs(margin - fixed_total - contingency):,.0f}**.\n")
    p("| The mix assumed | Backers |\n|---|---|")
    for k, q in mix.items():
        p(f"| {k} | {q} |")
    p("")
    rate = margin / pledged
    need = (fixed_total + contingency) / rate
    goal = int(-(-need // 5000) * 5000)
    avg = pledged / sum(mix.values())
    p(f"The margin is about **{rate:.0%} of every dollar pledged** at a run of 50 (est.). To carry the fixed costs, the")
    p(f"campaign must raise about **${need:,.0f}** in pledges.\n")
    p(f"**Proposed goal: ${goal:,}** (est.), about {goal / avg:.0f} backers at the mix's average pledge of ${avg:,.0f}.")
    p("Below it, a run of lamps would be made and the listings left unpaid, so the campaign should not fund. Above it, the")
    p("run grows toward 100 of each, the cost of a unit falls (the second margin table) and every lamp adds margin.\n")
    for label, cert in (("low", lo), ("high", hi)):
        f2 = fixed_total - (lo + hi) / 2 + cert
        p(f"- If the labs quote R3's {label} end (${cert:,}), the goal is about ${-(-(f2 * 1.15 / rate) // 5000) * 5000:,.0f}.")
    no_ul = fixed_total - (lo + hi) / 2 + (lo + hi) / 2 - 14000 - 10500
    p(f"- If the pre-seed pays for the two UL listings (midpoints $14,000 and $10,500), the goal is about"
      f" ${-(-(no_ul * 1.15 / rate) // 5000) * 5000:,.0f}.")
    p("\nR2's customer-funded path aims at $150k to $500k for the lamps; the goal is the floor, not the target.\n")

if __name__ == "__main__":
    main()
